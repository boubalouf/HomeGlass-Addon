"""Opérations partagées entre les routes de l'application et celles de l'éditeur."""

from __future__ import annotations

import hashlib
import json
import logging
from typing import Any

from ..ha.autogen import generate_layout

logger = logging.getLogger(__name__)


def build_autogenerated_layout(state: Any) -> dict[str, Any]:
    """Génère une mise en page layout v1 complète (tous les champs, ``null`` inclus)."""
    layout = generate_layout(state.cache)
    return layout.model_dump(by_alias=True, mode="json")


def ensure_published(state: Any) -> tuple[dict[str, Any], bool]:
    """Renvoie la version publiée, en la générant (révision 1) si elle n'existe pas."""
    document = state.layouts.get_published()
    if document is not None:
        return document, False

    logger.info(
        "Aucune mise en page publiée : génération automatique des %d entités en cache",
        len(state.cache.entities),
    )
    return state.layouts.publish(build_autogenerated_layout(state)), True


def layout_etag(document: dict[str, Any]) -> str:
    """ETag fort, dérivé de la révision et du contenu résolu pour l'appareil.

    La révision seule ne suffit pas : deux appareils peuvent recevoir des documents
    différents (profils). Le condensat garde l'ETag exact, la révision le rend lisible.
    """
    payload = json.dumps(
        document, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    digest = hashlib.sha256(payload).hexdigest()[:12]
    return f'"r{int(document.get("revision") or 0)}-{digest}"'


def etag_matches(header: str | None, etag: str) -> bool:
    """Compare un en-tête ``If-None-Match`` (liste, ``W/``, ``*``) à un ETag."""
    if not header:
        return False
    expected = _normalize_etag(etag)
    for candidate in header.split(","):
        candidate = candidate.strip()
        if candidate == "*":
            return True
        if candidate and _normalize_etag(candidate) == expected:
            return True
    return False


def _normalize_etag(value: str) -> str:
    return value.strip().removeprefix("W/").strip().strip('"')


async def notify_layout_updated(state: Any, revision: int) -> int:
    """Pousse ``layout_updated`` aux applications connectées."""
    return await state.hub.broadcast({"type": "layout_updated", "revision": int(revision)})


