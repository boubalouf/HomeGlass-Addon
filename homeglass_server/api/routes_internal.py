"""Routes de l'éditeur, accessibles uniquement via Ingress.

L'utilisateur y est déjà authentifié par Home Assistant : aucune vérification de jeton.
Le port API (8765) répond 404 sur ce préfixe grâce à la dépendance
[require_ingress][homeglass_server.api.deps.require_ingress].
"""

from __future__ import annotations

import json
import logging
from typing import Any

from fastapi import APIRouter, Body, Depends, HTTPException, Request
from fastapi.responses import JSONResponse, Response

from ..ha.autogen import exclusion_reason, generate_layout
from ..models.api import (
    AssetMeta,
    AutogenerateRequest,
    HaStatus,
    ProfileOverrides,
    StatusResponse,
)
from ..store.assets import AssetError
from ..store.repository import StoreError
from .deps import require_ingress
from .service import build_autogenerated_layout, notify_layout_updated

logger = logging.getLogger(__name__)

router = APIRouter(
    prefix="/internal",
    tags=["internal"],
    dependencies=[Depends(require_ingress)],
)


# ----------------------------------------------------------------------- diagnostics


@router.get("/status", response_model=StatusResponse, response_model_by_alias=True)
async def status(request: Request) -> StatusResponse:
    state = request.app.state
    connection = state.ha.state
    published = state.layouts.get_published()
    return StatusResponse(
        version=state.settings.version,
        ha_uuid=state.ha_uuid,
        ingress_port=state.settings.ingress_port,
        api_port=state.settings.api_port,
        published_revision=(published or {}).get("revision"),
        draft_exists=state.layouts.get_draft() is not None,
        devices=state.devices.count(),
        paired_devices=state.pairing.count(),
        assets=state.assets.count(),
        ha=HaStatus(
            connected=connection.connected,
            attempts=connection.attempts,
            last_error=connection.last_error,
            connected_since=(
                connection.connected_since.isoformat() if connection.connected_since else None
            ),
            version=connection.version,
            entities=len(state.cache.entities),
            areas=len(state.cache.areas),
        ),
    )


@router.get("/entities", summary="Entités Home Assistant connues du cache")
async def entities(request: Request) -> dict[str, Any]:
    cache = request.app.state.cache
    items = cache.entity_snapshot()
    for item in items:
        record = cache.entities.get(item["entityId"])
        item["excludedReason"] = exclusion_reason(record) if record else None
    return {"count": len(items), "entities": items}


@router.get("/areas", summary="Pièces Home Assistant connues du cache")
async def areas(request: Request) -> dict[str, Any]:
    items = request.app.state.cache.area_snapshot()
    return {"count": len(items), "areas": items}


# ------------------------------------------------------------------- mise en page


@router.post(
    "/layout/autogenerate",
    summary="Génère une mise en page layout v1 depuis Home Assistant",
)
async def autogenerate(
    request: Request,
    payload: AutogenerateRequest | None = Body(default=None),
) -> Response:
    state = request.app.state
    options = payload or AutogenerateRequest()
    if not state.cache.entities:
        logger.warning(
            "Génération automatique demandée sans données Home Assistant : "
            "la mise en page produite sera vide (voir /internal/status)"
        )

    document = build_autogenerated_layout(state)
    if not options.publish:
        return JSONResponse(document)

    published = state.layouts.publish(document)
    delivered = await notify_layout_updated(state, published["revision"])
    return JSONResponse({"layout": published, "delivered": delivered})


@router.get("/layout/draft", summary="Brouillon en cours d'édition")
async def get_draft(request: Request) -> dict[str, Any]:
    return {"layout": request.app.state.layouts.get_draft()}


@router.put("/layout/draft", summary="Enregistre et valide le brouillon")
async def put_draft(request: Request, payload: dict[str, Any] = Body(...)) -> dict[str, Any]:
    try:
        document = request.app.state.layouts.save_draft(_unwrap(payload))
    except StoreError as error:
        raise HTTPException(422, str(error)) from error
    return {"layout": document}


@router.get("/layout/published", summary="Version publiée")
async def get_published(request: Request) -> dict[str, Any]:
    return {"layout": request.app.state.layouts.get_published()}


@router.post("/layout/publish", summary="Publie le brouillon ou la mise en page fournie")
async def publish(
    request: Request,
    payload: dict[str, Any] | None = Body(default=None),
) -> dict[str, Any]:
    state = request.app.state
    document = _unwrap(payload) if payload else None
    try:
        published = state.layouts.publish(document)
    except StoreError as error:
        raise HTTPException(422, str(error)) from error

    delivered = await notify_layout_updated(state, published["revision"])
    return {"layout": published, "delivered": delivered}


@router.get("/layout/history", summary="Versions publiées (20 dernières)")
async def history(request: Request) -> dict[str, Any]:
    store = request.app.state.layouts
    return {"limit": store.history_limit, "versions": store.history()}


@router.get("/layout/versions/{revision}", summary="Contenu d'une version de l'historique")
async def get_version(revision: int, request: Request) -> dict[str, Any]:
    document = request.app.state.layouts.get_version(revision)
    if document is None:
        raise HTTPException(404, f"révision {revision} absente de l'historique")
    return {"layout": document}


@router.post("/layout/restore/{revision}", summary="Restaure une version (nouvelle révision)")
async def restore(revision: int, request: Request) -> dict[str, Any]:
    state = request.app.state
    try:
        restored = state.layouts.restore(revision)
    except StoreError as error:
        raise HTTPException(404, str(error)) from error

    delivered = await notify_layout_updated(state, restored["revision"])
    return {"layout": restored, "delivered": delivered}


