@router.post("/assets", status_code=201, summary="Envoie une image (10 Mo max)")
async def upload_asset(request: Request) -> Response:
    state = request.app.state
    limit = state.settings.max_asset_bytes

    declared_length = request.headers.get("content-length")
    if declared_length and declared_length.isdigit() and int(declared_length) > limit:
        raise HTTPException(413, f"fichier trop volumineux (maximum {limit} octets)")

    data = await request.body()
    declared_type = (request.headers.get("content-type") or "").split(";")[0].strip().lower()
    filename = request.headers.get("x-filename") or request.query_params.get("filename")

    try:
        meta = state.assets.save(
            data,
            filename=filename,
            declared_type=declared_type if declared_type.startswith("image/") else None,
        )
    except AssetError as error:
        message = str(error)
        raise HTTPException(413 if "volumineux" in message else 400, message) from error
    return JSONResponse(meta, status_code=201)


@router.get("/assets", summary="Ressources stockées")
async def list_assets(request: Request) -> dict[str, Any]:
    assets = request.app.state.assets.list()
    return {"count": len(assets), "assets": assets}


def _unwrap(payload: dict[str, Any] | None) -> dict[str, Any] | None:
    """Accepte un document layout nu ou enveloppé dans ``{"layout": …}``."""
    if not isinstance(payload, dict):
        return None
    if set(payload) == {"layout"} and isinstance(payload["layout"], dict):
        return payload["layout"]
    return payload


