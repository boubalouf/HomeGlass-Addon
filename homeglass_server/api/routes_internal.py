@router.put(
    "/devices/{device_id}/profile",
    summary="Surcharges de mise en page d'un appareil (ou du profil « default »)",
)
async def put_profile(
    device_id: str,
    request: Request,
    payload: ProfileOverrides = Body(...),
) -> dict[str, Any]:
    store = request.app.state.devices
    try:
        stored = store.set_profile(device_id, payload.model_dump(by_alias=True, mode="json"))
    except ValueError as error:
        raise HTTPException(422, str(error)) from error
    return {"deviceId": device_id, "profile": stored}


