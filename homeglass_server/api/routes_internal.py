@router.delete("/pairing/pending/{pairing_id}", summary="Annule une demande d'appairage")
async def cancel_pairing(pairing_id: str, request: Request) -> dict[str, Any]:
    if not request.app.state.pairing.cancel(pairing_id):
        raise HTTPException(404, "demande d'appairage inconnue")
    return {"cancelled": True, "pairingId": pairing_id}


@router.delete("/pairing/devices/{device_id}", summary="Révoque un appareil appairé")
async def revoke_paired_device(device_id: str, request: Request) -> dict[str, Any]:
    if not request.app.state.pairing.revoke(device_id):
        raise HTTPException(404, "appareil inconnu")
    return {"revoked": True, "deviceId": device_id}


